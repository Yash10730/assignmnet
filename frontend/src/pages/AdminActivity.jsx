import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import api, { errorMessage } from '../api/client';
import { Alert, Pagination, Spinner } from '../components/ui';
import { formatDate } from '../utils/format';

const EVENTS = [
  'ticket.created',
  'ticket.updated',
  'ticket.deleted',
  'ticket.status_changed',
  'ticket.resolved',
  'comment.added',
];

export default function AdminActivity() {
  const [data, setData] = useState(null);
  const [page, setPage] = useState(1);
  const [event, setEvent] = useState('');
  const [error, setError] = useState('');

  useEffect(() => {
    api
      .get('/admin/activity', { params: { page, limit: 20, ...(event && { event }) } })
      .then((r) => setData({ items: r.data.data, meta: r.data.meta }))
      .catch((e) => setError(errorMessage(e)));
  }, [page, event]);

  if (error) return <Alert>{error}</Alert>;
  if (!data) return <Spinner />;

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Activity log</h1>
          <p className="muted">Audit trail generated by the event system</p>
        </div>
        <select
          value={event}
          onChange={(e) => {
            setEvent(e.target.value);
            setPage(1);
          }}
        >
          <option value="">All events</option>
          {EVENTS.map((ev) => (
            <option key={ev} value={ev}>{ev}</option>
          ))}
        </select>
      </div>
      <div className="card table-wrap">
        <table>
          <thead>
            <tr>
              <th>When</th>
              <th>Event</th>
              <th>Description</th>
              <th>Ticket</th>
            </tr>
          </thead>
          <tbody>
            {data.items.map((a) => (
              <tr key={a.id}>
                <td className="muted nowrap">{formatDate(a.createdAt)}</td>
                <td><code>{a.event}</code></td>
                <td>{a.message}</td>
                <td>
                  {a.ticket ? <Link to={`/tickets/${a.ticket.id || a.ticket._id}`}>Open</Link> : <span className="muted">deleted</span>}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <Pagination meta={data.meta} onChange={setPage} />
    </>
  );
}
